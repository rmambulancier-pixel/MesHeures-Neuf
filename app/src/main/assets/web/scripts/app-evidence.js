  function norm(v){
    return String(v??'')
      .normalize('NFD').replace(/[\u0300-\u036f]/g,'')
      .toLowerCase().replace(/\s+/g,' ').trim();
  }

  function dailyType(c){
    if(!c || !String(c.id||'').startsWith('C18-'))return null;
    const day=String(c.jour_concerne||'').trim();
    if(!/^\d{4}-\d{2}-\d{2}$/.test(day))return null;
    const hay=norm([
      c.regle_violie,c.message,c.article_source,c.rule,c.type,c.code
    ].filter(v=>v!=null).join(' | '));

    if(/pause minimale.*20 min/.test(hay) || /6 h.*sans pause/.test(hay) || /pause.*20 min.*6 h/.test(hay))return 'pause20';
    if(/amplitude\s*>\s*14\s*h/.test(hay) || /amplitude.*14h/.test(hay))return 'amp14';
    if(/amplitude\s*>\s*12\s*h/.test(hay) || /amplitude.*12h/.test(hay))return 'amp12';
    if(/tte\s*>\s*12\s*h/.test(hay) || /tte.*12h/.test(hay))return 'tte12';
    if(/tte\s*>\s*10\s*h/.test(hay) || /tte.*10h/.test(hay))return 'tte10';
    return null;
  }

  function stillValid(c,type){
    const r=window.mhCalcDay?window.mhCalcDay(c.jour_concerne):cd(c.jour_concerne);
    if(!r)return false;
    const amp=Number(r.amp)||0, tte=Number(r.tte)||0, pz=Number(r.pz)||0;
    if(type==='pause20')return tte>=360 && pz<20;
    if(type==='amp14')return amp>14*60;
    if(type==='amp12')return amp>12*60 && amp<=14*60;
    if(type==='tte12')return tte>720;
    if(type==='tte10')return tte>600 && tte<=720;
    return true;
  }

